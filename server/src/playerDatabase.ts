// Generates an auction pool scaled to N managers * 15 cards
// Distributes realistic ratios across Tiers 1-4
export function generateAuctionPool(managerCount: number): PlayerCard[] {
  const totalCardsNeeded = Math.max(15, managerCount * 15);

  const t1 = MASTER_PLAYER_DATABASE.filter((p) => p.tier === 1);
  const t2 = MASTER_PLAYER_DATABASE.filter((p) => p.tier === 2);
  const t3 = MASTER_PLAYER_DATABASE.filter((p) => p.tier === 3);
  const t4 = MASTER_PLAYER_DATABASE.filter((p) => p.tier === 4);

  // Targets: ~20% Tier 1, ~30% Tier 2, ~30% Tier 3, ~20% Tier 4
  const t1Count = Math.max(2, Math.round(totalCardsNeeded * 0.2));
  const t2Count = Math.max(3, Math.round(totalCardsNeeded * 0.3));
  const t3Count = Math.max(3, Math.round(totalCardsNeeded * 0.3));
  const t4Count = totalCardsNeeded - (t1Count + t2Count + t3Count);

  function sampleWithReplacement<T>(arr: T[], count: number): T[] {
    const result: T[] = [];
    // First take shuffled unique items
    const shuffled = [...arr].sort(() => Math.random() - 0.5);
    for (let i = 0; i < count; i++) {
      const item = shuffled[i % shuffled.length];
      result.push(JSON.parse(JSON.stringify(item)));
    }
    return result;
  }

  const selectedT1 = sampleWithReplacement(t1, t1Count);
  const selectedT2 = sampleWithReplacement(t2, t2Count);
  const selectedT3 = sampleWithReplacement(t3, t3Count);
  const selectedT4 = sampleWithReplacement(t4, Math.max(2, t4Count));

  // Combine and shuffle the pool so tiers appear in exciting sequence
  const combined = [...selectedT1, ...selectedT2, ...selectedT3, ...selectedT4];
  return combined.sort(() => Math.random() - 0.5);
}

